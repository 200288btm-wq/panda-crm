// =====================================================================
// Подгруппы: что показывать, а что уже нет.
//
// Подгруппа — это занятие (инвариант с 24.08: у подгруппы не больше
// одного времени на день недели). Поэтому убрать её из расписания
// нельзя тем же жестом, каким правят опечатку в названии: за ней
// числятся отметки, журнал часов и выплаты, а начисления нигде
// не хранятся — они считаются заново из этой самой истории.
//
// Отсюда архив вместо удаления, ровно как у направлений и педагогов
// (см. lib/archive.js). База удалить подгруппу с историей не даст:
// внешний ключ attendance.group_id стоит на RESTRICT, остальные пять
// таблиц закрывает проверка block_delete_group_with_history.
//
// Каждое место, где читаются подгруппы, отвечает на один из двух
// РАЗНЫХ вопросов, и путать их нельзя:
//
//   «что можно выбрать сейчас»  → liveGroups     (архивные убраны)
//   «что было в этот день»      → groupsOnDate   (архивные до даты архивации)
//   «как это называлось»        → d.groups       (всё, включая архив)
//
// Третий случай — расшифровка прошлого: имя подгруппы в выплате
// за июль, в истории отметок, в списке ставок. Если отфильтровать
// архивные и там, история станет безымянной, а это ровно та потеря,
// ради предотвращения которой архив и заводился.
// =====================================================================

/** Подгруппа убрана из обращения? */
export const isGroupArchived = (g) => !!g?.archived_at

/**
 * Подгруппы, доступные для выбора сейчас.
 * Для списков выбора: карточка клиента, чипы педагога, ставки,
 * запись с сайта, настройки.
 */
export const liveGroups = (d) => (d?.groups || []).filter(g => !g.archived_at)

/**
 * Подгруппы, существовавшие на указанную дату (`ГГГГ-ММ-ДД`).
 *
 * Для календаря. Занятия рисуются из расписания, а не лежат в базе,
 * поэтому архивная подгруппа обязана гаснуть НЕ везде сразу, а начиная
 * с даты архивации: иначе отметки, уже поставленные за прошлые дни,
 * стало бы негде посмотреть. Та же логика, что у направлений
 * в getEventsForDate.
 */
export const groupsOnDate = (d, ds) =>
  (d?.groups || []).filter(g => !g.archived_at || ds < String(g.archived_at).slice(0, 10))

/**
 * Настоящие подгруппы — те, которых больше одной.
 * Одна подгруппа = обычное расписание направления (служебная
 * «Основная»), показывать её как выбор — шум.
 * Считается по живым: если из трёх подгрупп две в архиве, выбирать
 * человеку больше не из чего.
 */
export const realGroups = (d) => {
  const gs = liveGroups(d).slice().sort((a, b) => (a.sort_order || 0) - (b.sort_order || 0))
  return gs.length > 1 ? gs : []
}

/** Найти подгруппу по id среди всех, включая архивные. Для расшифровки прошлого. */
export const findGroup = (d, gid) => (d?.groups || []).find(g => +g.id === +gid) || null
